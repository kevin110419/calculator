# +
def sum(a, b):
    return a + b

# -
def sub(a, b):
    return a - b

# *
def mul(a, b):
    return a * b

# **
def square(a, b):
    return a ** b

# %
def mod(a, b):
    return a % b

# /
def div(a, b):
    if b == 0:
        return 0
    else:
        return a / b

# **3
def cube(a):
    return a**3